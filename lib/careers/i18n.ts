export const dictionaries: Record<Lang, Dict> = { en, kn, hi };
export type Key = keyof Dict;
export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>) {
  let s: string = dictionaries[lang][key] ?? en[key];
  for (const [k, v] of Object.entries(vars || {})) s = s.replace(`{${k}}`, String(v));
  return s;
}
/** Dictionary key for an option value, e.g. ("r_", "security_guard"). */
export const optionKey = (prefix: string, value: string) => (prefix + value) as Key;

/** Initial language: saved choice, then the browser language, then English. */
export function initialLang(): Lang {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === "en" || saved === "kn" || saved === "hi") return saved;
  } catch {}
  const nav = typeof navigator !== "undefined" ? navigator.languages || [navigator.language] : [];
  for (const l of nav) {
    const c = (l || "").toLowerCase();
    if (c.startsWith("kn")) return "kn";
    if (c.startsWith("hi")) return "hi";
    if (c.startsWith("en")) return "en";
  }
  return "en";
}
export function saveLang(lang: Lang) {
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch {}
  if (typeof document !== "undefined") document.documentElement.lang = languages.find((l) => l.code === lang)!.html;
}
